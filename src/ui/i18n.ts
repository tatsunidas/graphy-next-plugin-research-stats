export type Key = keyof (typeof T)["ja"];

export function makeT(locale: Locale) {
  return (key: Key, vars: Record<string, string | number> = {}) =>
    T[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export const toLocale = (s: string | undefined): Locale => (s && s.toLowerCase().startsWith("en") ? "en" : "ja");
